"""Deploy user_agent to Agent Runtime (DEC-0004, DEC-0010).

    uv run python interactive_agents/user_agent/deploy.py --env dev [--dry-run]

- Refuses uncommitted changes: the engine is labelled with the commit it runs.
- Stages `.build/agent_runtime/<commit>/`: the `user_agent` package and a `requirements.txt` exported from
  uv.lock (third-party packages only).
- Creates the engine `sdlc-user-agent-<env>` in the region, or updates it when it exists. It runs as the
  interactive agents' service account, which user_agent_mcp knows as the `user_agent` caller
  (identity.callers), and calls user_agent_mcp's URL with that account's ID token.
- Project, service account and user_agent_mcp's URL come from `terraform output` in infra/gcp unless given.
"""

import argparse
import base64
import io
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
COMPONENT = Path(__file__).resolve().parent
REGION = "europe-west3"
OPERATIONS = [
    "async_create_session",
    "async_get_session",
    "async_list_sessions",
    "async_delete_session",
    "async_stream_query",
]


def run(*args: str, cwd: Path = ROOT) -> str:
    return subprocess.run(list(args), cwd=cwd, capture_output=True, text=True, check=True).stdout.strip()


def terraform_output(name: str) -> str:
    tf = shutil.which("terraform") or "terraform"
    try:
        return run(tf, f"-chdir={ROOT / 'infra' / 'gcp'}", "output", "-raw", name)
    except (OSError, subprocess.CalledProcessError):
        return ""


def stage(commit: str) -> Path:
    target = ROOT / ".build" / "agent_runtime" / commit
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True)
    shutil.copytree(
        COMPONENT / "src" / "user_agent",
        target / "user_agent",
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "__main__.py"),
    )
    # The skills the workflows use (user_agent/skills.py reads them from the package).
    shutil.copytree(ROOT / "skills", target / "user_agent" / "skills")
    uv = shutil.which("uv") or "uv"
    requirements = run(
        uv, "export", "--package", "sdlc-user-agent", "--no-dev", "--no-hashes", "--no-emit-workspace", "--frozen"
    )
    (target / "requirements.txt").write_text(requirements, encoding="utf-8")
    return target


def class_methods(folder: Path) -> list[dict]:
    """The method schemas a source deploy needs, generated by the SDK from the staged application."""
    sys.path.insert(0, str(folder))
    try:
        from user_agent.runtime import create_app
        from vertexai._genai import _agent_engines_utils as engine_utils

        app = create_app()
        specs = engine_utils._generate_class_methods_spec_or_raise(agent=app, operations=app.register_operations())
        methods = [engine_utils._to_dict(spec) for spec in specs]
    except (ImportError, AttributeError) as exc:
        sys.exit(f"cannot generate class_methods with this vertexai SDK: {exc}")
    finally:
        sys.path.remove(str(folder))
    if sorted(m.get("name") for m in methods) != sorted(OPERATIONS):
        sys.exit(f"class_methods incomplete: {[m.get('name') for m in methods]}")
    return methods


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--env", default="dev")
    parser.add_argument("--region", default=REGION)
    parser.add_argument("--project", default="", help="default: terraform output project_id")
    parser.add_argument(
        "--service-account", default="", help="default: terraform output interactive_agents_service_account"
    )
    parser.add_argument(
        "--mcp-url", default="", help="user_agent_mcp's URL; default: terraform output user_agent_mcp_url"
    )
    parser.add_argument("--model", default="gemini-3.8-flash")
    parser.add_argument("--review-model", default="gemini-3.5-flash", help="The reviewers' model")
    parser.add_argument("--model-location", default="eu", help="Vertex AI location of the model (NFR-HOST-005)")
    parser.add_argument("--allow-dirty", action="store_true", help="deploy uncommitted code (tests only)")
    parser.add_argument("--dry-run", action="store_true", help="stage and print; deploy nothing")
    args = parser.parse_args(argv)

    if run("git", "status", "--porcelain") and not args.allow_dirty:
        sys.exit("uncommitted changes: commit first (the engine is labelled with its commit)")
    project = args.project or terraform_output("project_id")
    account = args.service_account or terraform_output("interactive_agents_service_account")
    mcp_url = (args.mcp_url or terraform_output("user_agent_mcp_url")).rstrip("/")
    if not (project and account and mcp_url):
        sys.exit("need --project, --service-account and --mcp-url (or the Terraform outputs)")
    commit = run("git", "rev-parse", "--short=12", "HEAD")
    folder = stage(commit)
    env = {
        "SDLC_MCP_URL": f"{mcp_url}/mcp",
        "SDLC_MCP_AUDIENCE": mcp_url,  # user_agent_mcp's PUBLIC_URL
        "SDLC_CALLER_AUTH": "id_token",
        "SDLC_MCP_TIMEOUT": "30",  # a scaled-to-zero user_agent_mcp needs a few seconds
        "SDLC_AGENT_MODEL": args.model,
        "SDLC_REVIEW_MODEL": args.review_model,
        "SDLC_MODEL_LOCATION": args.model_location,
    }
    name = f"sdlc-user-agent-{args.env}"
    print(f"staged {folder.relative_to(ROOT)} (commit {commit}); engine {name} in {project}/{args.region}")
    print(f"runs as {account}; environment: {', '.join(f'{k}={v}' for k, v in env.items())}")

    os.environ.setdefault("GOOGLE_CLOUD_PROJECT", project)
    import vertexai

    # The SDK archives each source package under the path it is given and refuses paths outside the working
    # directory: run from the staged folder so `user_agent/` sits at the top of the archive.
    os.chdir(folder)
    config = {
        "display_name": name,
        "description": "user_agent: knowledge search and brainstorming for the signed-in user",
        "source_packages": ["user_agent", "requirements.txt"],
        "entrypoint_module": "user_agent.app",
        "entrypoint_object": "app",
        "requirements_file": "requirements.txt",
        "class_methods": class_methods(folder),
        "python_version": "3.12",
        "env_vars": env,
        "service_account": account,
        "labels": {"git_commit": commit, "env": args.env},
    }
    print("class methods: " + ", ".join(f"{m['name']} ({m.get('api_mode', '')})" for m in config["class_methods"]))
    if args.dry_run:
        import tarfile

        from vertexai._genai import _agent_engines_utils as engine_utils

        tarball = engine_utils._create_base64_encoded_tarball(source_packages=config["source_packages"])
        with tarfile.open(fileobj=io.BytesIO(base64.b64decode(tarball)), mode="r:gz") as tar:
            names = tar.getnames()
        print(f"archive: {len(names)} entries, top level {sorted({n.split('/')[0] for n in names})}")
        return 0
    client = vertexai.Client(project=project, location=args.region)
    existing = [e for e in client.agent_engines.list() if e.api_resource.display_name == name]
    if existing:
        engine = client.agent_engines.update(name=existing[0].api_resource.name, config=config)
        print(f"updated {engine.api_resource.name}")
    else:
        engine = client.agent_engines.create(config=config)
        print(f"created {engine.api_resource.name}")
    print(f"sdlc_ui's SDLC_AGENT_URL: https://{args.region}-aiplatform.googleapis.com/v1/{engine.api_resource.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
