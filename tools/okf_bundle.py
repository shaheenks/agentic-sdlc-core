"""Build and lint the OKF specification bundle in spec/.

    uv run python tools/okf_bundle.py build   # regenerate index files, traceability.md and the mkdocs nav
    uv run python tools/okf_bundle.py lint    # check the bundle; exit 1 on any problem

Conventions it enforces are in spec/conventions.md.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec"
MKDOCS = ROOT / "mkdocs.yml"

LAYERS = ["experience", "control", "execution", "capability", "knowledge", "records", "platform"]
AREAS = {
    "SURF": "Surfaces", "IDN": "Identity", "TEAM": "Teams", "AUTHZ": "Authorization",
    "CFG": "Configuration", "WFL": "Workflows", "TRIG": "Triggers", "HUM": "Human tasks",
    "AGT": "Agent steps", "SKILL": "Skills", "CONN": "Connections", "KNOW": "Knowledge",
    "ART": "Artifacts", "MDL": "Models", "SDLC": "SDLC flow",
    "HOST": "Hosting", "ARCH": "Architecture", "SEC": "Security", "PRIV": "Privacy",
    "AUD": "Auditability", "OBS": "Observability", "REL": "Reliability", "PERF": "Performance",
    "OPS": "Operability",
}
REQ_TYPES = {"Functional Requirement": "functional", "Non-Functional Requirement": "non-functional"}
BUILT = {"live", "built", "stub"}
GENERATED = "<!-- Generated by tools/okf_bundle.py build. Do not edit by hand. -->"


@dataclass
class Concept:
    path: Path
    meta: dict
    body: str

    @property
    def cid(self) -> str:
        return "/" + self.path.relative_to(SPEC).with_suffix("").as_posix()

    @property
    def name(self) -> str:
        return self.path.stem


def load() -> list[Concept]:
    concepts = []
    for p in sorted(SPEC.rglob("*.md")):
        if p.name in ("index.md", "log.md"):
            continue
        text = p.read_text(encoding="utf-8")
        m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
        if not m:
            continue
        meta = yaml.safe_load(m.group(1)) or {}
        if meta.get("type"):
            concepts.append(Concept(p, meta, m.group(2)))
    return concepts


def section(body: str, heading: str) -> str:
    m = re.search(rf"^# {re.escape(heading)}\n(.*?)(?=^# |\Z)", body, re.S | re.M)
    return m.group(1) if m else ""


def linked_names(text: str) -> set[str]:
    return {Path(t).stem for t in re.findall(r"\]\(([^)#]+\.md)\)", text)}


def by_type(concepts, t):
    return [c for c in concepts if c.meta.get("type") == t]


def requirements(concepts):
    return [c for c in concepts if c.meta.get("type") in REQ_TYPES]


def req_sort_key(c: Concept):
    area = c.meta.get("x-area", "")
    order = list(AREAS).index(area) if area in AREAS else len(AREAS)
    return (c.meta["type"] != "Functional Requirement", order, c.name)


# ------------------------------------------------------------------ build
def build() -> None:
    concepts = load()
    comps = by_type(concepts, "Component")
    reqs = sorted(requirements(concepts), key=req_sort_key)
    satisfied_by: dict[str, list[Concept]] = {r.cid: [] for r in reqs}
    for c in comps:
        for rid in c.meta.get("x-satisfies") or []:
            satisfied_by.setdefault(rid, []).append(c)

    # components/index.md
    lines = []
    for layer in LAYERS:
        members = [c for c in comps if c.meta.get("x-layer") == layer]
        if members:
            lines += [f"# {layer.capitalize()}", ""]
            lines += [f"* [{c.meta['title']}]({c.name}.md) - "
                      f"{'*Retired.* ' if c.meta.get('status') == 'deprecated' else ''}{c.meta.get('description', '')}"
                      for c in members]
            lines.append("")
    (SPEC / "components" / "index.md").write_text("\n".join(lines), encoding="utf-8")

    # requirements/<kind>/index.md and requirements/index.md
    top = []
    for rtype, folder in REQ_TYPES.items():
        members = [r for r in reqs if r.meta["type"] == rtype]
        lines, top_lines = [], [f"# {rtype}s", "", f"* [All {rtype.lower()}s]({folder}/index.md)", ""]
        for area in AREAS:
            group = [r for r in members if r.meta.get("x-area") == area]
            if not group:
                continue
            lines += [f"# {AREAS[area]}", ""]
            lines += [f"* [{r.name}: {r.meta['title']}]({r.name}.md) - {r.meta.get('description', '')}" for r in group]
            lines.append("")
            top_lines.append(f"* [{AREAS[area]}]({folder}/index.md#{AREAS[area].lower().replace(' ', '-')}) - {len(group)}")
        (SPEC / "requirements" / folder / "index.md").write_text("\n".join(lines), encoding="utf-8")
        top += top_lines + [""]
    (SPEC / "requirements" / "index.md").write_text("\n".join(top), encoding="utf-8")

    # traceability.md
    t = ["---", "type: Traceability Matrix", "title: Traceability",
         "description: Generated matrix from requirements to the components that satisfy them, with gaps.",
         "tags: [meta, generated]", "---", "", GENERATED, "",
         "# Requirements to components", "",
         "| Requirement | Priority | Implementation | Satisfied by |", "|---|---|---|---|"]
    for r in reqs:
        sub = REQ_TYPES[r.meta["type"]]
        cs = ", ".join(f"[{c.meta['title']}](components/{c.name}.md)" for c in satisfied_by.get(r.cid, []))
        t.append(f"| [{r.name}](requirements/{sub}/{r.name}.md) {r.meta['title']} | {r.meta.get('x-priority', '')} "
                 f"| {r.meta.get('x-implementation', '')} | {cs or '-'} |")
    gaps = [r for r in reqs if not satisfied_by.get(r.cid)]
    t += ["", "# Gaps", "", "Requirements no component satisfies yet:", ""]
    t += [f"* [{r.name}: {r.meta['title']}](requirements/{REQ_TYPES[r.meta['type']]}/{r.name}.md)" for r in gaps] or ["* None."]
    (SPEC / "traceability.md").write_text("\n".join(t) + "\n", encoding="utf-8")

    # decisions/index.md
    decisions = sorted(by_type(concepts, "Decision"), key=lambda c: c.name)
    if decisions:
        lines = ["# Decisions", ""]
        lines += [f"* [{d.name}: {d.meta['title']}]({d.name}.md) - `{d.meta.get('x-state', '')}` - "
                  f"{d.meta.get('description', '')}" for d in decisions]
        (SPEC / "decisions" / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # mkdocs nav
    nav = ["nav:", "  - Home: index.md", "  - Conventions: conventions.md", "  - Components:",
           "      - components/index.md"]
    for layer in LAYERS:
        members = [c for c in comps if c.meta.get("x-layer") == layer]
        if members:
            nav.append(f"      - {layer.capitalize()}:")
            nav += [f"          - \"{c.meta['title']}\": components/{c.name}.md" for c in members]
    nav += ["  - Requirements:", "      - requirements/index.md"]
    for rtype, folder in REQ_TYPES.items():
        nav += [f"      - {rtype}s:", f"          - requirements/{folder}/index.md"]
        for area in AREAS:
            group = [r for r in reqs if r.meta["type"] == rtype and r.meta.get("x-area") == area]
            if group:
                nav.append(f"          - {AREAS[area]}:")
                nav += [f"              - \"{r.name} {r.meta['title']}\": requirements/{folder}/{r.name}.md" for r in group]
    if decisions:
        nav += ["  - Decisions:", "      - decisions/index.md"]
        nav += [f"      - \"{d.name} {d.meta['title']}\": decisions/{d.name}.md" for d in decisions]
    nav += ["  - Traceability: traceability.md", "  - Change log: log.md"]
    text = MKDOCS.read_text(encoding="utf-8")
    text = re.sub(r"^nav:\n.*\Z", "\n".join(nav) + "\n", text, flags=re.S | re.M)
    MKDOCS.write_text(text, encoding="utf-8")
    print(f"built: {len(comps)} components, {len(reqs)} requirements, {len(gaps)} gaps")


# ------------------------------------------------------------------ lint
def lint() -> int:
    concepts = load()
    ids = {c.cid for c in concepts}
    comps = by_type(concepts, "Component")
    reqs = requirements(concepts)
    errors: list[str] = []

    def err(c: Concept, msg: str):
        errors.append(f"{c.path.relative_to(ROOT).as_posix()}: {msg}")

    for c in concepts:
        required = ("title", "description") if c.meta["type"] == "Traceability Matrix" else ("title", "description", "status")
        for key in required:
            if not c.meta.get(key):
                err(c, f"missing `{key}`")
        for target in re.findall(r"\]\(([^)#]+\.md)(?:#[^)]*)?\)", c.body):
            if not target.startswith(("http:", "https:", "/")) and not (c.path.parent / target).resolve().exists():
                err(c, f"broken link {target}")
        if c.meta.get("status") == "stable" and not any(
            str(v.get("by", "")).startswith("human:") for v in c.meta.get("verified") or []
        ):
            err(c, "`stable` without a `verified` entry by human:<id>")

    for r in reqs:
        area = r.meta.get("x-area")
        if not re.fullmatch(r"N?FR-[A-Z]+-\d{3}", r.name):
            err(r, "file name is not a requirement ID")
        elif r.name.split("-")[1] != area:
            err(r, f"`x-area` {area} does not match the ID")
        if area not in AREAS:
            err(r, f"unknown area {area}")
        if r.meta.get("x-priority") not in ("must", "should", "could"):
            err(r, "`x-priority` must be must, should or could")
        if r.meta.get("x-implementation") not in BUILT | {"planned", "parked"}:
            err(r, "`x-implementation` must be live, built, stub, planned or parked")
        for s in ("Statement", "Acceptance criteria"):
            if not section(r.body, s).strip():
                err(r, f"missing `# {s}`")

    for d in by_type(concepts, "Decision"):
        if not re.fullmatch(r"DEC-\d{4}", d.name):
            err(d, "file name is not a decision ID")
        if d.meta.get("x-state") not in ("proposed", "accepted", "rejected", "superseded"):
            err(d, "`x-state` must be proposed, accepted, rejected or superseded")
        for ref in d.meta.get("x-affects") or []:
            if ref not in ids:
                err(d, f"unknown concept {ref}")
        for s in ("Context", "Options", "Decision", "Consequences"):
            if not section(d.body, s).strip():
                err(d, f"missing `# {s}`")

    satisfied = set()
    for c in comps:
        if c.meta.get("x-layer") not in LAYERS:
            err(c, f"unknown `x-layer` {c.meta.get('x-layer')}")
        deps = c.meta.get("x-depends-on") or []
        sats = c.meta.get("x-satisfies") or []
        satisfied |= set(sats)
        for ref in deps + sats:
            if ref not in ids:
                err(c, f"unknown concept {ref}")
        if {Path(d).name for d in deps} != linked_names(section(c.body, "Depends on")):
            err(c, "`x-depends-on` and `# Depends on` differ")
        if {Path(s).name for s in sats} != linked_names(section(c.body, "Requirements")):
            err(c, "`x-satisfies` and `# Requirements` differ")
        if not sats and c.meta.get("status") != "deprecated":
            err(c, "satisfies no requirement")
        if c.meta.get("status") == "deprecated" and c.meta.get("superseded_by") and c.meta["superseded_by"] not in ids:
            err(c, f"unknown `superseded_by` {c.meta['superseded_by']}")

    for r in reqs:
        if r.meta.get("x-implementation") in BUILT and r.meta.get("status") != "deprecated" and r.cid not in satisfied:
            err(r, "built requirement with no satisfying component")

    for e in errors:
        print(e)
    print(f"lint: {len(concepts)} concepts, {len(errors)} problem(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "build":
        build()
    elif cmd == "lint":
        sys.exit(lint())
    else:
        sys.exit(__doc__)
