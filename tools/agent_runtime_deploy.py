"""Deploying an ADK agent package to Agent Runtime (DEC-0004, DEC-0007), shared by the agents' deploy.py scripts.

- Refuses uncommitted changes: the engine is labelled with the commit it runs.
- Stages `.build/agent_runtime/<package>-<commit>/`: the package, the workspace libraries it imports at runtime (not
  in the exported requirements), the skills, and a `requirements.txt` exported from uv.lock (third-party only).
- Generates the class methods from the staged application and checks them against the expected operations.
- Creates the engine `<display name>` in the region, or updates it when it exists.
"""

import base64
import io
import os
import shutil
import subprocess
import sys
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


@dataclass(frozen=True)
class Target:
    package: str  # the import package, such as user_agent
    component: Path  # the component folder, with src/<package>
    uv_package: str  # the uv project name, such as sdlc-user-agent
    operations: list[str]
    description: str
    runtime_libs: list[str] = field(default_factory=lambda: ["sdlc_adk"])
    with_skills: bool = True


def run(*args: str, cwd: Path = ROOT) -> str:
    return subprocess.run(list(args), cwd=cwd, capture_output=True, text=True, check=True).stdout.strip()


def terraform_output(name: str) -> str:
    tf = shutil.which("terraform") or "terraform"
    try:
        return run(tf, f"-chdir={ROOT / 'infra' / 'gcp'}", "output", "-raw", name)
    except (OSError, subprocess.CalledProcessError):
        return ""


def require_clean(allow_dirty: bool) -> str:
    if run("git", "status", "--porcelain") and not allow_dirty:
        sys.exit("uncommitted changes: commit first (the engine is labelled with its commit)")
    return run("git", "rev-parse", "--short=12", "HEAD")


def stage(target: Target, commit: str) -> Path:
    folder = ROOT / ".build" / "agent_runtime" / f"{target.package}-{commit}"
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    shutil.copytree(
        target.component / "src" / target.package,
        folder / target.package,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "__main__.py"),
    )
    for lib in target.runtime_libs:  # workspace libraries are not in requirements.txt (--no-emit-workspace)
        shutil.copytree(ROOT / "libs" / lib / "src" / lib, folder / lib, ignore=ignore)
    if target.with_skills:  # read from the package (<package>/skills)
        shutil.copytree(ROOT / "skills", folder / target.package / "skills")
    uv = shutil.which("uv") or "uv"
    requirements = run(
        uv, "export", "--package", target.uv_package, "--no-dev", "--no-hashes", "--no-emit-workspace", "--frozen"
    )
    (folder / "requirements.txt").write_text(requirements, encoding="utf-8")
    return folder


def class_methods(target: Target, folder: Path) -> list[dict]:
    """The method schemas a source deploy needs, generated by the SDK from the staged application."""
    sys.path.insert(0, str(folder))
    try:
        runtime = __import__(f"{target.package}.runtime", fromlist=["create_app"])
        from vertexai._genai import _agent_engines_utils as engine_utils

        app = runtime.create_app()
        specs = engine_utils._generate_class_methods_spec_or_raise(agent=app, operations=app.register_operations())
        methods = [engine_utils._to_dict(spec) for spec in specs]
    except (ImportError, AttributeError) as exc:
        sys.exit(f"cannot generate class_methods with this vertexai SDK: {exc}")
    finally:
        sys.path.remove(str(folder))
    if sorted(m.get("name") for m in methods) != sorted(target.operations):
        sys.exit(f"class_methods incomplete: {[m.get('name') for m in methods]}")
    return methods


def deploy(
    target: Target,
    *,
    env_name: str,
    region: str,
    project: str,
    account: str,
    env_vars: Mapping[str, str],
    commit: str,
    dry_run: bool,
) -> str | None:
    """Stages and deploys; returns the engine's resource name (None on a dry run)."""
    folder = stage(target, commit)
    name = f"sdlc-{target.package.replace('_', '-')}-{env_name}"
    print(f"staged {folder.relative_to(ROOT)} (commit {commit}); engine {name} in {project}/{region}")
    print(f"runs as {account}; environment: {', '.join(f'{k}={v}' for k, v in env_vars.items())}")
    os.environ.setdefault("GOOGLE_CLOUD_PROJECT", project)
    import vertexai

    # The SDK archives each source package under the path it is given and refuses paths outside the working
    # directory: run from the staged folder so the package sits at the top of the archive.
    os.chdir(folder)
    config = {
        "display_name": name,
        "description": target.description,
        "source_packages": [target.package, *target.runtime_libs, "requirements.txt"],
        "entrypoint_module": f"{target.package}.app",
        "entrypoint_object": "app",
        "requirements_file": "requirements.txt",
        "class_methods": class_methods(target, folder),
        "python_version": "3.12",
        "env_vars": dict(env_vars),
        "service_account": account,
        "labels": {"git_commit": commit, "env": env_name},
    }
    print("class methods: " + ", ".join(f"{m['name']} ({m.get('api_mode', '')})" for m in config["class_methods"]))
    if dry_run:
        import tarfile

        from vertexai._genai import _agent_engines_utils as engine_utils

        tarball = engine_utils._create_base64_encoded_tarball(source_packages=config["source_packages"])
        with tarfile.open(fileobj=io.BytesIO(base64.b64decode(tarball)), mode="r:gz") as tar:
            names = tar.getnames()
        print(f"archive: {len(names)} entries, top level {sorted({n.split('/')[0] for n in names})}")
        return None
    client = vertexai.Client(project=project, location=region)
    existing = [e for e in client.agent_engines.list() if e.api_resource.display_name == name]
    if existing:
        engine = client.agent_engines.update(name=existing[0].api_resource.name, config=config)
        print(f"updated {engine.api_resource.name}")
    else:
        engine = client.agent_engines.create(config=config)
        print(f"created {engine.api_resource.name}")
    return engine.api_resource.name
